SET TIME ZONE 'Asia/Jakarta';

-- Trigger Helper: otomatis memperbarui kolom updated_at saat UPDATE
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. USERS (Akun Pemain, Profil, & Preferensi Onboarding)
CREATE TABLE IF NOT EXISTS users (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                    VARCHAR(100) NOT NULL,
  username_tag            VARCHAR(60)  NOT NULL UNIQUE,
  email                   VARCHAR(150) NOT NULL UNIQUE,
  password_hash           VARCHAR(255) NOT NULL,
  phone                   VARCHAR(25)  DEFAULT NULL,
  city                    VARCHAR(80)  NOT NULL DEFAULT 'Kota Malang',
  bio                     TEXT         DEFAULT NULL,
  avatar_path             VARCHAR(255) DEFAULT NULL,
  banner_path             VARCHAR(255) DEFAULT NULL,
  pref_category           VARCHAR(20)  DEFAULT NULL CHECK (pref_category IN ('esports', 'olahraga', 'keduanya')),
  pref_games_json         TEXT         DEFAULT NULL,
  questionnaire_completed BOOLEAN      NOT NULL DEFAULT FALSE,
  is_active               BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_lower_email ON users (LOWER(email));

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2. PASSWORD RESETS (OTP 6 Digit + Token Reset via Email PHPMailer)
CREATE TABLE IF NOT EXISTS password_resets (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email            VARCHAR(150) NOT NULL,
  otp_hash         VARCHAR(255) NOT NULL,
  reset_token_hash VARCHAR(255) DEFAULT NULL,
  attempts         SMALLINT     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  expires_at       TIMESTAMP    NOT NULL,
  verified_at      TIMESTAMP    DEFAULT NULL,
  used_at          TIMESTAMP    DEFAULT NULL,
  created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pr_email_created ON password_resets (LOWER(email), created_at DESC);

-- 3. MABAR SESSIONS (Room Mabar Esports & Olahraga Fisik)
CREATE TABLE IF NOT EXISTS mabar_sessions (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug           VARCHAR(64)  NOT NULL UNIQUE,
  host_user_id   INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  category       VARCHAR(20)  NOT NULL DEFAULT 'esports' CHECK (category IN ('esports', 'olahraga')),
  game           VARCHAR(80)  NOT NULL,
  title          VARCHAR(160) NOT NULL,
  description    TEXT         DEFAULT NULL,
  city           VARCHAR(80)  NOT NULL DEFAULT 'Online',
  place_label    VARCHAR(180) NOT NULL,
  schedule_label VARCHAR(100) DEFAULT NULL,
  start_time     VARCHAR(10)  NOT NULL DEFAULT '19:00',
  end_time       VARCHAR(10)  NOT NULL DEFAULT '22:00',
  mode           VARCHAR(60)  NOT NULL DEFAULT 'Ranked',
  join_rule      VARCHAR(20)  NOT NULL DEFAULT 'Ask For Join' CHECK (join_rule IN ('Langsung Gabung', 'Otomatis', 'Ask For Join')),
  max_slot       SMALLINT     NOT NULL DEFAULT 5 CHECK (max_slot >= 2),
  rules_json     TEXT         DEFAULT NULL,
  specs_json     TEXT         DEFAULT NULL,
  is_featured    BOOLEAN      NOT NULL DEFAULT FALSE,
  status         VARCHAR(20)  NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'full', 'ongoing', 'finished', 'cancelled')),
  created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_mabar_sessions_cat_status ON mabar_sessions (category, status);
CREATE INDEX IF NOT EXISTS idx_mabar_sessions_host ON mabar_sessions (host_user_id);

DROP TRIGGER IF EXISTS trg_mabar_sessions_updated_at ON mabar_sessions;
CREATE TRIGGER trg_mabar_sessions_updated_at
  BEFORE UPDATE ON mabar_sessions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 4. MABAR PARTICIPANTS (Host, Anggota Lobby, & Antrian Ask For Join)
CREATE TABLE IF NOT EXISTS mabar_participants (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id INTEGER     NOT NULL REFERENCES mabar_sessions (id) ON DELETE CASCADE,
  user_id    INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role       VARCHAR(20) NOT NULL DEFAULT 'member' CHECK (role IN ('host', 'member', 'pending')),
  rank_label VARCHAR(60) DEFAULT NULL,
  is_ready   BOOLEAN     NOT NULL DEFAULT FALSE,
  joined_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_session_user UNIQUE (session_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_mp_user ON mabar_participants (user_id);

-- 5. SCRIM MATCHES (Cari Lawan Scrim & Sparring Tim)
CREATE TABLE IF NOT EXISTS scrim_matches (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                 VARCHAR(64)  NOT NULL UNIQUE,
  creator_user_id      INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  category             VARCHAR(20)  NOT NULL DEFAULT 'esports' CHECK (category IN ('esports', 'olahraga')),
  game                 VARCHAR(80)  NOT NULL,
  team_name            VARCHAR(120) NOT NULL,
  logo_initial         VARCHAR(8)   NOT NULL DEFAULT 'TM',
  tier                 VARCHAR(80)  NOT NULL DEFAULT 'Kompetitif',
  tier_badge           VARCHAR(40)  NOT NULL DEFAULT 'Kompetitif',
  tier_color           VARCHAR(20)  NOT NULL DEFAULT 'red',
  format_label         VARCHAR(100) NOT NULL,
  format_short         VARCHAR(20)  NOT NULL DEFAULT 'BO3',
  schedule_label       VARCHAR(100) NOT NULL,
  day_category         VARCHAR(20)  NOT NULL DEFAULT 'hari_ini' CHECK (day_category IN ('hari_ini', 'weekend', 'lainnya')),
  match_type           VARCHAR(20)  NOT NULL DEFAULT 'online' CHECK (match_type IN ('online', 'offline')),
  location_label       VARCHAR(180) NOT NULL,
  city                 VARCHAR(80)  NOT NULL,
  captain_name         VARCHAR(100) NOT NULL,
  captain_rank         VARCHAR(60)  DEFAULT NULL,
  notes                TEXT         DEFAULT NULL,
  status               VARCHAR(20)  NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'matched', 'confirmed', 'cancelled')),
  is_featured          BOOLEAN      NOT NULL DEFAULT FALSE,
  challenger_user_id   INTEGER      DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
  challenger_team_name VARCHAR(120) DEFAULT NULL,
  challenger_contact   VARCHAR(80)  DEFAULT NULL,
  challenger_message   TEXT         DEFAULT NULL,
  host_ready           BOOLEAN      NOT NULL DEFAULT FALSE,
  challenger_ready     BOOLEAN      NOT NULL DEFAULT FALSE,
  room_id              VARCHAR(80)  DEFAULT NULL,
  room_password        VARCHAR(80)  DEFAULT NULL,
  created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_scrim_cat_status ON scrim_matches (category, status);

DROP TRIGGER IF EXISTS trg_scrim_matches_updated_at ON scrim_matches;
CREATE TRIGGER trg_scrim_matches_updated_at
  BEFORE UPDATE ON scrim_matches
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 6. TOURNAMENTS (Turnamen Komunitas Lokal)
CREATE TABLE IF NOT EXISTS tournaments (
  id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug                    VARCHAR(64)  NOT NULL UNIQUE,
  creator_user_id         INTEGER      DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
  title                   VARCHAR(180) NOT NULL,
  game                    VARCHAR(80)  NOT NULL,
  category                VARCHAR(20)  NOT NULL DEFAULT 'esports' CHECK (category IN ('esports', 'olahraga')),
  status_label            VARCHAR(40)  NOT NULL DEFAULT 'AKAN DATANG',
  status_badge            VARCHAR(60)  NOT NULL DEFAULT 'Slot Terbuka',
  status_type             VARCHAR(20)  NOT NULL DEFAULT 'upcoming' CHECK (status_type IN ('live', 'upcoming', 'done')),
  is_featured             BOOLEAN      NOT NULL DEFAULT FALSE,
  city                    VARCHAR(80)  NOT NULL,
  location                VARCHAR(180) NOT NULL,
  schedule_text           VARCHAR(100) NOT NULL,
  prize_pool              VARCHAR(80)  NOT NULL DEFAULT 'Gratis',
  fee_label               VARCHAR(80)  NOT NULL DEFAULT 'Gratis',
  max_teams               SMALLINT     NOT NULL DEFAULT 16 CHECK (max_teams >= 2),
  format_label            VARCHAR(120) NOT NULL,
  organizer               VARCHAR(120) NOT NULL,
  poster_path             VARCHAR(255) DEFAULT NULL,
  game_icon               VARCHAR(255) DEFAULT NULL,
  description             TEXT         DEFAULT NULL,
  prize_distribution_json TEXT         DEFAULT NULL,
  bracket_json            TEXT         DEFAULT NULL,
  winner_team             VARCHAR(120) DEFAULT NULL,
  runner_up_team          VARCHAR(120) DEFAULT NULL,
  final_score             VARCHAR(30)  DEFAULT NULL,
  created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tournaments_type_cat ON tournaments (status_type, category);

DROP TRIGGER IF EXISTS trg_tournaments_updated_at ON tournaments;
CREATE TRIGGER trg_tournaments_updated_at
  BEFORE UPDATE ON tournaments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 7. TOURNAMENT TEAMS (Peserta & Roster Tim Turnamen)
CREATE TABLE IF NOT EXISTS tournament_teams (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id   INTEGER      NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
  user_id         INTEGER      DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
  team_name       VARCHAR(120) NOT NULL,
  captain_name    VARCHAR(100) NOT NULL,
  captain_contact VARCHAR(80)  DEFAULT NULL,
  city            VARCHAR(80)  DEFAULT NULL,
  roster_json     TEXT         DEFAULT NULL,
  seed_label      VARCHAR(20)  DEFAULT NULL,
  status          VARCHAR(20)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tt_tournament ON tournament_teams (tournament_id);

-- 8. TOURNAMENT MATCHES (Bagan & Jadwal Pertandingan Turnamen)
CREATE TABLE IF NOT EXISTS tournament_matches (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tournament_id  INTEGER      NOT NULL REFERENCES tournaments (id) ON DELETE CASCADE,
  round_name     VARCHAR(60)  NOT NULL,
  match_order    SMALLINT     NOT NULL DEFAULT 1,
  team_a_name    VARCHAR(120) NOT NULL DEFAULT 'TBD',
  team_b_name    VARCHAR(120) NOT NULL DEFAULT 'TBD',
  score_a        SMALLINT     DEFAULT NULL,
  score_b        SMALLINT     DEFAULT NULL,
  winner_name    VARCHAR(120) DEFAULT NULL,
  schedule_label VARCHAR(80)  DEFAULT NULL,
  status         VARCHAR(20)  NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'live', 'finished'))
);

CREATE INDEX IF NOT EXISTS idx_tm_tournament ON tournament_matches (tournament_id);

-- 9. CHAT THREADS & MESSAGES (Direct Message Antar Pemain)
CREATE TABLE IF NOT EXISTS chat_threads (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_key  VARCHAR(80)  NOT NULL UNIQUE,
  user_one_id INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  user_two_id INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  subtitle    VARCHAR(140) DEFAULT NULL,
  updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ct_users ON chat_threads (user_one_id, user_two_id);

DROP TRIGGER IF EXISTS trg_chat_threads_updated_at ON chat_threads;
CREATE TRIGGER trg_chat_threads_updated_at
  BEFORE UPDATE ON chat_threads
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS chat_messages (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id      INTEGER   NOT NULL REFERENCES chat_threads (id) ON DELETE CASCADE,
  sender_user_id INTEGER   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  body           TEXT      NOT NULL,
  is_read        BOOLEAN   NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cm_thread_created ON chat_messages (thread_id, created_at);

-- 10. NOTIFICATIONS (Pusat Notifikasi Terpadu MabarLokal)
CREATE TABLE IF NOT EXISTS notifications (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  category     VARCHAR(20)  NOT NULL DEFAULT 'sistem' CHECK (category IN ('mabar', 'scrim', 'turnamen', 'chat', 'sistem')),
  title        VARCHAR(160) NOT NULL,
  message      TEXT         NOT NULL,
  action_label VARCHAR(60)  DEFAULT NULL,
  href         VARCHAR(255) DEFAULT NULL,
  action_type  VARCHAR(40)  DEFAULT NULL,
  meta_json    TEXT         DEFAULT NULL,
  is_read      BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_notif_user_read ON notifications (user_id, is_read, created_at DESC);
